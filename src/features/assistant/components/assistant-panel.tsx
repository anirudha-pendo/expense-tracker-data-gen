import { useRef } from "react";
import { Plus } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Sheet, SheetContent, SheetDescription, SheetHeader, SheetTitle, SheetTrigger } from "@/components/ui/sheet";
import { Tooltip, TooltipContent, TooltipTrigger } from "@/components/ui/tooltip";
import { useAssistant } from "../state/assistant-context";
import { AssistantAlertBar } from "./assistant-alert";
import { AssistantTrigger } from "./assistant-trigger";
import { Composer } from "./composer";
import { MessageList } from "./message-list";
import { StatusAnnouncer } from "./status-announcer";

export function AssistantPanel() {
  const { open, setOpen, composerRef, composerDisabled, messages, newChat } = useAssistant();
  const contentRef = useRef<HTMLDivElement>(null);
  return (
    <Sheet open={open} onOpenChange={setOpen}>
      <SheetTrigger asChild>
        <AssistantTrigger />
      </SheetTrigger>
      <SheetContent
        ref={contentRef}
        side="right"
        className="gap-0 p-0 data-[side=right]:w-full data-[side=right]:sm:max-w-md motion-reduce:data-open:animate-none motion-reduce:data-closed:animate-none"
        onOpenAutoFocus={(event) => {
          // Start in the composer, not on Retry or Jump to latest.
          event.preventDefault();
          composerRef.current?.focus();
        }}
      >
        <SheetHeader className="flex-row items-center justify-between gap-3 border-b border-border/40 px-5 py-3 pr-12">
          <SheetTitle className="font-mono text-[10px] font-normal tracking-widest uppercase text-muted-foreground">
            Assistant
          </SheetTitle>
          <div className="flex items-center gap-2">
            <span aria-hidden className="font-mono text-[10px] text-muted-foreground/40">
              esc to close
            </span>
            <Tooltip>
              <TooltipTrigger asChild>
                <Button
                  variant="ghost"
                  size="icon-sm"
                  aria-label="New chat"
                  disabled={messages.length === 0}
                  onClick={() => {
                    // Focus before the clear re-renders, so focus never falls to the body off a now-disabled button.
                    (composerDisabled ? contentRef.current : composerRef.current)?.focus();
                    newChat();
                  }}
                >
                  <Plus />
                </Button>
              </TooltipTrigger>
              <TooltipContent className="font-mono text-[10px] tracking-widest uppercase motion-reduce:data-[state=delayed-open]:animate-none motion-reduce:data-closed:animate-none">
                New chat
              </TooltipContent>
            </Tooltip>
          </div>
          <SheetDescription className="sr-only">
            Ask about your money. Answers use your workspace data and are generated by Anthropic.
          </SheetDescription>
        </SheetHeader>
        <MessageList />
        <StatusAnnouncer />
        <AssistantAlertBar />
        <Composer />
      </SheetContent>
    </Sheet>
  );
}
